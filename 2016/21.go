// Day 21: Scrambled Letters and Hash
//
// The input is a list of operations that scramble a password: swapping
// positions or letters, rotating left, right or "based on position of letter
// X", reversing a span, and moving a letter from one position to another.
//
// Part 1 is the result of scrambling "abcdefgh".
// Part 2 is the password that scrambles to "fbgdceah".
//
// The operations are parsed once and applied to a fixed-size byte array.
// Rather than inverting each operation (rotation based on a letter is awkward
// to undo), part 2 scrambles every ordering of the eight letters - 40320 of
// them, generated by Heap's algorithm in its iterative form - until one gives
// the target.
package main

import (
	"errors"
	"fmt"
	"os"
	"strconv"
	"strings"
)

// Limits on the puzzle input, so that every loop over it has a fixed bound.
const (
	inputPath     = "inputs/21.txt"
	maxInputBytes = 1 << 20
	maxLines      = 1_000
	maxLen        = 16
)

// The operations.
const (
	swapPosition = iota
	swapLetter
	rotateLeft
	rotateRight
	rotateBased
	reverseSpan
	movePosition
)

// operation is one parsed line; x and y are positions, steps or letters.
type operation struct {
	kind int
	x, y int
}

// password is the string being scrambled.
type password struct {
	b [maxLen]byte
	n int
}

// readLines returns the lines of the input file, which must hold between 1 and
// maxInputBytes bytes and at most maxLines lines.
func readLines(path string) ([]string, error) {
	if path == "" {
		return nil, errors.New("no input path given")
	}
	content, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if len(content) == 0 || len(content) > maxInputBytes {
		return nil, fmt.Errorf("%s: size %d is outside 1..%d bytes", path, len(content), maxInputBytes)
	}
	lines := strings.Split(strings.TrimRight(string(content), "\r\n"), "\n")
	if len(lines) > maxLines {
		return nil, fmt.Errorf("%s: %d lines, more than the %d allowed", path, len(lines), maxLines)
	}
	return lines, nil
}

// numbers reads the words at positions i and j as small numbers.
func numbers(w []string, i, j int) (x, y int, err error) {
	if i >= len(w) || j >= len(w) {
		return 0, 0, fmt.Errorf("operation %q is too short", strings.Join(w, " "))
	}
	if x, err = strconv.Atoi(w[i]); err != nil {
		return 0, 0, fmt.Errorf("invalid number in %q: %w", strings.Join(w, " "), err)
	}
	if y, err = strconv.Atoi(w[j]); err != nil {
		return 0, 0, fmt.Errorf("invalid number in %q: %w", strings.Join(w, " "), err)
	}
	if x < 0 || y < 0 || x >= maxLen*4 || y >= maxLen*4 {
		return 0, 0, fmt.Errorf("number out of range in %q", strings.Join(w, " "))
	}
	return x, y, nil
}

// parseOperation reads one line.
func parseOperation(line string) (operation, error) {
	w := strings.Fields(line)
	if len(w) < 4 {
		return operation{}, fmt.Errorf("malformed operation %q", line)
	}
	var op operation
	var err error
	switch w[0] + " " + w[1] {
	case "swap position":
		op.kind = swapPosition
		op.x, op.y, err = numbers(w, 2, 5)
	case "swap letter":
		if len(w) != 6 || len(w[2]) != 1 || len(w[5]) != 1 {
			return operation{}, fmt.Errorf("malformed operation %q", line)
		}
		op.kind, op.x, op.y = swapLetter, int(w[2][0]), int(w[5][0])
	case "rotate left", "rotate right":
		op.kind = rotateLeft
		if w[1] == "right" {
			op.kind = rotateRight
		}
		op.x, op.y, err = numbers(w, 2, 2)
	case "rotate based":
		if len(w[len(w)-1]) != 1 {
			return operation{}, fmt.Errorf("malformed operation %q", line)
		}
		op.kind, op.x = rotateBased, int(w[len(w)-1][0])
	case "reverse positions":
		op.kind = reverseSpan
		op.x, op.y, err = numbers(w, 2, 4)
	case "move position":
		op.kind = movePosition
		op.x, op.y, err = numbers(w, 2, 5)
	default:
		return operation{}, fmt.Errorf("unknown operation %q", line)
	}
	return op, err
}

// index returns where letter c sits in the password.
func (p *password) index(c int) (int, error) {
	if c < 'a' || c > 'z' {
		return 0, fmt.Errorf("%c is not a letter", c)
	}
	for i := range p.n {
		if int(p.b[i]) == c {
			return i, nil
		}
	}
	return 0, fmt.Errorf("letter %c is not in %s", c, p.b[:p.n])
}

// rotate turns the password right by k places (negative k turns left).
func (p *password) rotate(k int) error {
	if p.n < 1 || p.n > maxLen {
		return fmt.Errorf("cannot rotate a password of length %d", p.n)
	}
	k = ((k % p.n) + p.n) % p.n
	old := p.b
	for i := range p.n {
		p.b[(i+k)%p.n] = old[i]
	}
	return nil
}

// apply carries out one operation.
func (p *password) apply(op operation) error {
	if p.n < 1 || p.n > maxLen {
		return fmt.Errorf("password length %d is outside 1..%d", p.n, maxLen)
	}
	if (op.kind == swapPosition || op.kind == reverseSpan || op.kind == movePosition) && (op.x >= p.n || op.y >= p.n) {
		return fmt.Errorf("operation %+v reaches past position %d", op, p.n-1)
	}
	switch op.kind {
	case swapPosition:
		p.b[op.x], p.b[op.y] = p.b[op.y], p.b[op.x]
	case swapLetter:
		i, err := p.index(op.x)
		if err != nil {
			return err
		}
		j, err := p.index(op.y)
		if err != nil {
			return err
		}
		p.b[i], p.b[j] = p.b[j], p.b[i]
	case rotateLeft:
		return p.rotate(-op.x)
	case rotateRight:
		return p.rotate(op.x)
	case rotateBased:
		i, err := p.index(op.x)
		if err != nil {
			return err
		}
		return p.rotate(1 + i + i/4) // one more when the index is at least 4
	case reverseSpan:
		for i, j := min(op.x, op.y), max(op.x, op.y); i < j; i, j = i+1, j-1 {
			p.b[i], p.b[j] = p.b[j], p.b[i]
		}
	case movePosition:
		c := p.b[op.x]
		copy(p.b[op.x:p.n-1], p.b[op.x+1:p.n]) // take it out
		copy(p.b[op.y+1:p.n], p.b[op.y:p.n-1]) // open a gap at y
		p.b[op.y] = c
	default:
		return fmt.Errorf("unknown operation %d", op.kind)
	}
	return nil
}

// newPassword copies text into a password.
func newPassword(text string) (password, error) {
	if text == "" || len(text) > maxLen {
		return password{}, fmt.Errorf("password %q is not 1..%d letters", text, maxLen)
	}
	if strings.Trim(text, "abcdefghijklmnopqrstuvwxyz") != "" {
		return password{}, fmt.Errorf("password %q holds something other than letters", text)
	}
	var p password
	p.n = copy(p.b[:], text)
	return p, nil
}

// scramble applies every operation to p, which is passed by value.
func scramble(p password, ops []operation) (password, error) {
	if p.n < 1 || p.n > maxLen {
		return password{}, fmt.Errorf("password length %d is outside 1..%d", p.n, maxLen)
	}
	if len(ops) == 0 {
		return password{}, errors.New("no operations")
	}
	for _, op := range ops {
		if err := p.apply(op); err != nil {
			return password{}, err
		}
	}
	return p, nil
}

// unscramble finds the arrangement of the target's letters that scrambles to
// the target.
func unscramble(target password, ops []operation) (password, error) {
	n := target.n
	if n < 1 || n > 10 {
		return password{}, fmt.Errorf("cannot try every ordering of %d letters", n)
	}
	letters := target
	var counters [maxLen]int

	// Heap's algorithm: each pass of the loop yields the next permutation.
	tried, i := 0, 0
	for step := 0; step < 4_000_000; step++ {
		got, err := scramble(letters, ops)
		if err != nil {
			return password{}, err
		}
		if got == target {
			return letters, nil
		}
		tried++
		for k := 0; k < maxLen && i < n && counters[i] >= i; k++ {
			counters[i] = 0
			i++
		}
		if i == n {
			return password{}, fmt.Errorf("none of the %d orderings scrambles to %s", tried, target.b[:n])
		}
		if i%2 == 0 {
			letters.b[0], letters.b[i] = letters.b[i], letters.b[0]
		} else {
			letters.b[counters[i]], letters.b[i] = letters.b[i], letters.b[counters[i]]
		}
		counters[i]++
		i = 0
	}
	return password{}, errors.New("permutation walk did not finish")
}

func day21(path string) error {
	lines, err := readLines(path)
	if err != nil {
		return err
	}
	ops := make([]operation, 0, len(lines))
	for _, line := range lines {
		if strings.TrimSpace(line) == "" {
			continue
		}
		op, err := parseOperation(line)
		if err != nil {
			return err
		}
		ops = append(ops, op)
	}

	plain, err := newPassword("abcdefgh")
	if err != nil {
		return err
	}
	target, err := newPassword("fbgdceah")
	if err != nil {
		return err
	}
	scrambled, err := scramble(plain, ops)
	if err != nil {
		return err
	}
	original, err := unscramble(target, ops)
	if err != nil {
		return err
	}
	if _, err := fmt.Printf("Part 1: %s\nPart 2: %s\n", scrambled.b[:scrambled.n], original.b[:original.n]); err != nil {
		return err
	}
	return nil
}

func main() {
	path := inputPath
	if len(os.Args) > 1 {
		path = os.Args[1] // another input, such as an example from the puzzle
	}
	if err := day21(path); err != nil {
		// Nothing more can be done if writing to stderr fails too.
		_, _ = fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}
